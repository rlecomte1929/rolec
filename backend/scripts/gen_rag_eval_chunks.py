"""
W3-4 — generate the deterministic eval chunk fixture from the golden query set.

The golden queries (backend/tests/fixtures/rag_eval/queries.jsonl) reference
`expected_chunk_ids` but there is no retrievable chunk corpus for them, so the
context-precision eval scores 0.0 in CI. This generator emits one synthetic chunk
per unique expected id — corridor-scoped, with a deterministic body that overlaps
the retriever's per-corridor query (so retrieval is stable) — into
backend/tests/fixtures/rag_eval/chunks.jsonl.

Bodies are synthetic (no real policy text): the fixture exists to make the eval
deterministic + non-zero so CI can gate on retrieval-pipeline regressions, not to
measure real-world relevance. Re-run after editing queries.jsonl:

    python backend/scripts/gen_rag_eval_chunks.py
"""
from __future__ import annotations

import json
import os
import sys
from collections import defaultdict
from pathlib import Path

_REPO_ROOT = Path(__file__).resolve().parents[2]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from backend.scripts.eval_rag_context_precision import (  # noqa: E402
    _PATHWAY_DEFAULTS,
    _normalize_corridor,
)

_QUERIES = _REPO_ROOT / "backend/tests/fixtures/rag_eval/queries.jsonl"
_OUT = _REPO_ROOT / "backend/tests/fixtures/rag_eval/chunks.jsonl"


def _load_queries():
    out = []
    for line in _QUERIES.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith('{"_meta'):
            continue
        out.append(json.loads(line))
    return out


def _topic_words(chunk_id: str, corridor_db: str) -> str:
    """Distinctive words from the chunk id, minus the corridor/abbrev prefix."""
    parts = chunk_id.lower().split("_")
    drop = set(corridor_db.lower().split("_")) | {"bc", "lsv", "pt", "visa"}
    words = [p for p in parts if p and p not in drop]
    return " ".join(words) or chunk_id.lower()


def _build_body(chunk_id: str, corridor_db: str, corridor_arrow: str, pathway: str) -> str:
    origin, _, dest = corridor_arrow.partition("→")
    topic = _topic_words(chunk_id, corridor_db)
    # Overlaps the retriever's _build_query ("<pathway> immigration requirements
    # for a ... national relocating <ORIGIN→DEST>") so retrieval is corridor-scoped
    # and stable; the topic words keep each chunk distinct content.
    return (
        f"{pathway} immigration requirements for a national relocating "
        f"{corridor_arrow}. {origin} to {dest} {pathway} requirement: {topic}. "
        f"{corridor_db} {pathway} {topic} official rule."
    )


def main() -> None:
    queries = _load_queries()
    # chunk_id -> corridor info from the first query that references it.
    info: dict[str, dict] = {}
    refs: dict[str, int] = defaultdict(int)
    for q in queries:
        corridor_arrow = _normalize_corridor(q["corridor"])          # 'IN→DE'
        corridor_db = corridor_arrow.replace("→", "_")               # 'IN_DE'
        pathway = _PATHWAY_DEFAULTS.get(corridor_arrow, "long_stay_visa")
        for cid in q.get("expected_chunk_ids", []):
            refs[cid] += 1
            info.setdefault(cid, {
                "corridor_arrow": corridor_arrow,
                "corridor_db": corridor_db,
                "pathway": pathway,
            })

    rows = []
    for cid in sorted(info):
        meta = info[cid]
        rows.append({
            "chunk_id": cid,
            "corridor": meta["corridor_db"],
            "pathway_type": meta["pathway"],
            "trust_tier": 1,
            "source_url": f"https://gov.example/immigration_rule/{cid}",
            "body": _build_body(cid, meta["corridor_db"], meta["corridor_arrow"], meta["pathway"]),
        })

    with open(_OUT, "w", encoding="utf-8") as f:
        f.write(json.dumps({
            "_meta": "Generated by backend/scripts/gen_rag_eval_chunks.py from "
                     "queries.jsonl — do not edit by hand. Synthetic bodies; the "
                     "fixture exists to make the context-precision eval deterministic.",
        }) + "\n")
        for r in rows:
            f.write(json.dumps(r, separators=(",", ":")) + "\n")

    by_corridor: dict[str, int] = defaultdict(int)
    for r in rows:
        by_corridor[r["corridor"]] += 1
    print(f"wrote {len(rows)} chunks -> {_OUT.relative_to(_REPO_ROOT)}")
    print("by corridor:", dict(sorted(by_corridor.items())))


if __name__ == "__main__":
    main()
