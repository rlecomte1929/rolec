# ─────────────────────────────────────────────────────────────────────────────
# NO — fødselsnummer Mod-11
# ─────────────────────────────────────────────────────────────────────────────


class TestNoFodselsnummer:
    """The substantive test class — Mod-11 is the only validator with real logic.

    Test vectors are Mod-11-valid synthetic FNRs generated by the
    construction algorithm in `compute_fnr()` (see the C2-02b fixture
    README for full provenance). All three are used in the no_01 /
    no_02 / no_03 tax-cert fixtures.
    """

    # Known-good Mod-11-valid FNRs (synthetic, generated for ReloPass fixtures)
    HANSEN = "14058510131"  # DOB 14.05.1985, ind 101 (male)
    JOHANSEN = "23079010006"  # DOB 23.07.1990, ind 100 (female)
    ANDERSEN = "09019210070"  # DOB 09.01.1992, ind 100 (female)

    def test_valid_hansen(self) -> None:
        assert is_valid_no_fodselsnummer(self.HANSEN) is True

    def test_valid_johansen(self) -> None:
        assert is_valid_no_fodselsnummer(self.JOHANSEN) is True

    def test_valid_andersen(self) -> None:
        assert is_valid_no_fodselsnummer(self.ANDERSEN) is True

    def test_invalid_last_digit_flipped(self) -> None:
        # HANSEN with the second check digit incremented — catches single-digit OCR errors.
        assert is_valid_no_fodselsnummer("14058510132") is False

    def test_invalid_penultimate_digit_flipped(self) -> None:
        # HANSEN with the first check digit changed — catches that the second
        # check digit depends on the first.
        assert is_valid_no_fodselsnummer("14058510231") is False

    def test_invalid_swapped_check_digits(self) -> None:
        # HANSEN with check digits swapped (k1=3, k2=1 → swap to k1=1, k2=3).
        # If the algorithm only checked digit count, this would slip through.
        # Mod-11 catches it because the inputs to k2 include k1.
        # HANSEN k1=1, k2=3? Let's verify: HANSEN is "14058510131", last 3 = "131",
        # so check digits are 1, 3, 1 — wait, FNR is 11 digits, positions 0-10.
        # HANSEN[9] = '3', HANSEN[10] = '1'. So swapping gives "14058510113".
        assert is_valid_no_fodselsnummer("14058510113") is False

    @pytest.mark.parametrize(
        "bad",
        [
            "",
            "1405851013",  # 10 digits
            "140585101312",  # 12 digits
            "1405851013a",  # contains letter
            "14-05-85-1013-1",  # contains hyphens
            "00000000000",  # all zeros (technically passes Mod-11 sum=0 → k=0, k=0)
        ],
    )
    def test_invalid_format(self, bad) -> None:
        # Note: "00000000000" passes the format regex but Mod-11 on sum=0
        # gives k1 = 11 - 0 = 11 → 0. Same for k2. So the all-zeros FNR
        # actually PASSES Mod-11. This is a known curiosity of the algorithm;
        # in production, Skatteetaten reserves the all-zero combo.
        # Hence the test only asserts the truly-malformed inputs fail.
        if bad == "00000000000":
            # Document the curiosity, don't assert failure
            assert is_valid_no_fodselsnummer(bad) is True
        else:
            assert is_valid_no_fodselsnummer(bad) is False

    def test_construction_algorithm_round_trip(self) -> None:
        """Re-derive the check digits from the first 9 digits and confirm
        the validator agrees with the construction algorithm.

        This is the test that proves the validator implements the same
        Mod-11 spec as the generator that produced the fixtures.
        """
        weights1 = (3, 7, 6, 1, 8, 9, 4, 5, 2)
        weights2 = (5, 4, 3, 2, 7, 6, 5, 4, 3, 2)
        for base9 in ("140585101", "230790100", "090192100"):
            digits = [int(d) for d in base9]
            s1 = sum(w * d for w, d in zip(weights1, digits))
            k1 = 11 - (s1 % 11)
            if k1 == 11:
                k1 = 0
            if k1 == 10:
                continue  # invalid combo, skip
            digits10 = digits + [k1]
            s2 = sum(w * d for w, d in zip(weights2, digits10))
            k2 = 11 - (s2 % 11)
            if k2 == 11:
                k2 = 0
            if k2 == 10:
                continue
            constructed = base9 + str(k1) + str(k2)
            assert is_valid_no_fodselsnummer(constructed) is True, (
                f"Round-trip failed for {constructed}"
            )


# ─────────────────────────────────────────────────────────────────────────────
# tax_id_format_finding — unified emitter
# ─────────────────────────────────────────────────────────────────────────────


class TestTaxIdFormatFinding:
    def test_none_tax_id_returns_none(self) -> None:
        assert tax_id_format_finding(country="FRA", tax_id=None) is None
        assert tax_id_format_finding(country="DEU", tax_id=None) is None
        assert tax_id_format_finding(country="NOR", tax_id=None) is None

    def test_fr_valid_returns_none(self) -> None:
        assert tax_id_format_finding(country="FRA", tax_id="1234567890123") is None

    def test_fr_invalid_returns_warn(self) -> None:
        f = tax_id_format_finding(country="FRA", tax_id="123456789012")  # 12 digits
        assert isinstance(f, Finding)
        assert f.severity == "WARN"
        assert f.code == "TAX_ID_FORMAT_INVALID_FR"
        assert "13-digit" in f.message

    def test_de_valid_returns_none(self) -> None:
        assert tax_id_format_finding(country="DEU", tax_id="12345678901") is None

    def test_de_invalid_returns_warn(self) -> None:
        f = tax_id_format_finding(country="DEU", tax_id="1234567890")  # 10 digits
        assert isinstance(f, Finding)
        assert f.severity == "WARN"
        assert f.code == "TAX_ID_FORMAT_INVALID_DE"

    def test_no_valid_returns_none(self) -> None:
        assert (
            tax_id_format_finding(country="NOR", tax_id=TestNoFodselsnummer.HANSEN)
            is None
        )

    def test_no_invalid_mod_11_returns_warn(self) -> None:
        f = tax_id_format_finding(country="NOR", tax_id="14058510132")  # last digit flipped
        assert isinstance(f, Finding)
        assert f.severity == "WARN"
        assert f.code == "TAX_ID_FORMAT_INVALID_NO"
        assert "Mod-11" in f.message
        assert "UDI" in f.message

    def test_finding_is_immutable(self) -> None:
        f = tax_id_format_finding(country="FRA", tax_id="bad")
        assert f is not None
        with pytest.raises((AttributeError, TypeError)):
            f.code = "OTHER"  # type: ignore[misc]
