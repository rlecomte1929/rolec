# ─────────────────────────────────────────────────────────────────────────────
# FR — numéro fiscal de référence (SPI)
# ─────────────────────────────────────────────────────────────────────────────


class TestFrSpi:
    def test_valid_13_digit_spi(self) -> None:
        assert is_valid_fr_spi("1234567890123") is True

    def test_valid_spi_with_leading_zero(self) -> None:
        assert is_valid_fr_spi("0234567890123") is True

    @pytest.mark.parametrize(
        "bad",
        [
            "",
            "123456789012",  # 12 digits
            "12345678901234",  # 14 digits
            "12345678901a3",  # contains letter
            "12 34 56 78 90 12 3",  # contains spaces
            "1234-5678-90123",  # contains hyphens
            None,  # would be passed as None in practice
        ],
    )
    def test_invalid_spi(self, bad) -> None:
        # is_valid_fr_spi accepts str only via re.match — None goes through `s or ""`
        assert is_valid_fr_spi(bad) is False if bad is not None else is_valid_fr_spi("") is False


